import os
from typing import Dict, Any, Optional
from datetime import datetime, timezone
from app.config import settings

class GeminiAiService:
    """
    Google Gemini Generative AI Service for Environmental Intelligence.
    Synthesizes real-time multi-sensor telemetry, statistical anomaly signals,
    and diurnal trajectory forecasts into natural language health diagnostics
    and strategic mitigation recommendations.
    """
    def __init__(self):
        self.api_key = settings.GEMINI_API_KEY
        self.default_model = "gemini-1.5-flash"

    def analyze_air_quality(
        self,
        telemetry: Dict[str, float],
        aqi_data: Dict[str, Any],
        forecast_data: Dict[str, Any],
        anomaly_data: Dict[str, Any],
        custom_key: Optional[str] = None
    ) -> Dict[str, Any]:
        active_key = custom_key.strip() if custom_key and custom_key.strip() else self.api_key

        prompt = f"""You are an expert Environmental Health Scientist, Atmospheric Chemist, and Industrial Hygiene AI.
Analyze the following real-time air quality telemetry captured from an Arduino edge sensor node:

LIVE SENSOR READINGS:
- PM2.5 (Fine Combustion Particulate): {telemetry.get('pm25', 0)} µg/m³
- PM10 (Coarse Abrasive Dust): {telemetry.get('pm10', 0)} µg/m³
- CO2 (Carbon Dioxide / Indoor Stagnation): {telemetry.get('co2', 400)} ppm
- CO (Carbon Monoxide): {telemetry.get('co', 0.5)} ppm
- VOC (Volatile Organic Compounds Index): {telemetry.get('voc', 80)} pts
- Temperature: {telemetry.get('temp', 22.0)} °C
- Relative Humidity: {telemetry.get('hum', 50.0)} %

EPA AQI EVALUATION:
- Overall AQI: {aqi_data.get('aqi', 0)} ({aqi_data.get('category', 'Moderate')})
- Primary Dominant Pollutant: {aqi_data.get('primary_pollutant', 'PM2.5')}

AI ML TRAJECTORY FORECAST:
- Trend Direction: {forecast_data.get('trend_direction', 'STABLE')} ({forecast_data.get('trend_rate_pct', 0)}%/hr)
- 1-Hour Horizon PM2.5 Prediction: {forecast_data.get('forecasts', [{}])[2].get('predicted_pm25', 'N/A') if len(forecast_data.get('forecasts', [])) > 2 else 'N/A'} µg/m³
- Early Warning: {forecast_data.get('early_warning', 'Nominal')}

EDGE ANOMALY DETECTION:
- Anomaly Flag: {'ANOMALY DETECTED' if anomaly_data.get('detected') else 'NOMINAL'}
- Anomaly Score: {anomaly_data.get('score_percentage', 0)}%
- Anomaly Classification: {anomaly_data.get('anomaly_type', 'Nominal')}

Please provide a concise, structured intelligence report:
1. EXECUTIVE SYNTHESIS: A crisp 2-3 sentence overview of immediate ambient risk.
2. CAUSAL ATTRIBUTION: Most likely physical, atmospheric, or anthropogenic causes of this reading (e.g. traffic exhaust, thermal boundary compression, indoor ventilation deficit, solvent off-gassing).
3. VULNERABLE POPULATION ADVICE: Specific medical precautions for asthmatics, children, and elderly.
4. ACTIONABLE MITIGATION PLAN: Exact concrete actions (e.g., when to open/close windows, purifier fan stages, mask requirements).
Keep the tone professional, scientific, and clear. Avoid robotic fluff.
"""

        try:
            import google.generativeai as genai
            genai.configure(api_key=active_key)
            model = genai.GenerativeModel(self.default_model)
            response = model.generate_content(prompt)
            
            return {
                "status": "SUCCESS",
                "source": "Google Gemini (gemini-1.5-flash)",
                "content": response.text,
                "timestamp": datetime.now(timezone.utc).isoformat(),
                "is_live_gemini": True,
                "key_configured": bool(active_key)
            }
        except Exception as e:
            err_msg = str(e)
            is_disabled = "SERVICE_DISABLED" in err_msg or "has not been used in project" in err_msg
            is_invalid_key = "API_KEY_INVALID" in err_msg or "400" in err_msg

            # Provide clean fallback synthesis generated by the internal expert rule system
            fallback_text = self._generate_fallback_synthesis(telemetry, aqi_data, forecast_data, anomaly_data)

            return {
                "status": "FALLBACK_SYNTHESIS",
                "source": "Edge Environmental Intelligence (Local ML Synthesis)",
                "content": fallback_text,
                "timestamp": datetime.now(timezone.utc).isoformat(),
                "is_live_gemini": False,
                "key_configured": bool(active_key),
                "gemini_notice": (
                    "To enable direct Gemini AI cloud reasoning, enable the Generative Language API on your Google Cloud project (https://console.developers.google.com/apis/api/generativelanguage.googleapis.com/overview) or generate a free Gemini key at https://aistudio.google.com/."
                    if is_disabled else
                    f"Gemini connection: {err_msg[:140]}..."
                )
            }

    def _generate_fallback_synthesis(
        self,
        telemetry: Dict[str, float],
        aqi_data: Dict[str, Any],
        forecast_data: Dict[str, Any],
        anomaly_data: Dict[str, Any]
    ) -> str:
        pm25 = telemetry.get("pm25", 35.0)
        co2 = telemetry.get("co2", 640.0)
        aqi = aqi_data.get("aqi", 102)
        cat = aqi_data.get("category", "Moderate")
        trend = forecast_data.get("trend_direction", "STABLE")

        return f"""### 🔬 EXECUTIVE SYNTHESIS
Ambient air quality currently ranks as **{cat}** with an overall AQI of **{aqi}**, predominantly driven by fine particulate matter PM2.5 ({pm25:.1f} µg/m³). Atmospheric conditions exhibit a **{trend}** trajectory over the upcoming multi-hour horizon.

### 🚗 CAUSAL ATTRIBUTION
The particulate signature (fine-to-coarse ratio > 0.52) correlates strongly with combustion aerosol emissions, consistent with localized urban vehicular traffic and diurnal boundary layer compaction. Indoor CO₂ ({int(co2)} ppm) indicates moderate occupancy relative to effective fresh-air volume exchange.

### 🛡️ VULNERABLE POPULATION ADVICE
Sensitive cohorts—particularly individuals with asthma, COPD, or developing pulmonary systems in young children—should curtail strenuous outdoor aerobic workouts. General healthy adults may continue standard activities but should remain cognizant of changing evening peaks.

### ⚡ ACTIONABLE MITIGATION PLAN
1. **Filtration:** Engage mechanical air purifiers with true-HEPA and active carbon filtration stages.
2. **Ventilation:** If outdoor PM2.5 rises above 35 µg/m³, avoid opening raw external windows; utilize filtered mechanical air exchange (ERV/HRV) to dissipate indoor CO₂ without importing outside particulates.
3. **Protective Measures:** In the event of further particulate increases above AQI 150, equip N95 respirators for mandatory outdoor commuting."""

gemini_ai_service = GeminiAiService()
